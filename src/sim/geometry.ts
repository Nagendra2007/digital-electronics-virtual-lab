/**
 * True when every pin of a part is a whole number of hole pitches away from its
 * first pin, i.e. the part can be seated in the board with all legs in holes.
 */
export function seatsOnBoard(model: ComponentModel): boolean {
  const l = layoutOf(model);
  if (!l.pins.length) return false;
  const [first, ...rest] = l.pins;
  return rest.every(
    (p) => (p.x - first.x) % PIN_PITCH === 0 && (p.y - first.y) % PIN_PITCH === 0,
  );
}

/** Breadboard geometry is generated by `breadboard.ts` and cached here. */
export const boardLayouts = new Map<string, Layout>();

export function layoutOf(model: ComponentModel, comp?: PlacedComponent): Layout {
  if (model.pkg === 'DIP14') return dipLayout(14);
  if (model.pkg === 'DIP16') return dipLayout(16);

  if (model.category === 'board') {
    const key = `${model.type}:${comp?.props?.cols ?? 'default'}`;
    const cached = boardLayouts.get(key);
    if (cached) return cached;
  }

  const spec = MODULE_LAYOUTS[model.type]?.() ?? {
    w: 100,
    h: 60,
    pins: model.pins.map((p, i) => ({ n: p.n, x: 0, y: 20 + i * 20, side: 'L' as const })),
  };
  return { ...spec, bodyX: 0, bodyY: 0, bodyW: spec.w, bodyH: spec.h };
}

/** Bounding box of a component after rotation. */
export function boundsOf(model: ComponentModel, comp: PlacedComponent) {
  const l = layoutOf(model, comp);
  const swapped = comp.rot === 90 || comp.rot === 270;
  return {
    x: comp.x,
    y: comp.y,
    w: swapped ? l.h : l.w,
    h: swapped ? l.w : l.h,
  };
}

/** Map a point in the component's own frame into workspace coordinates. */
export function toWorld(
  comp: PlacedComponent,
  l: Layout,
  x: number,
  y: number,
): { x: number; y: number } {
  switch (comp.rot) {
    case 90:
      return { x: comp.x + l.h - y, y: comp.y + x };
    case 180:
      return { x: comp.x + l.w - x, y: comp.y + l.h - y };
    case 270:
      return { x: comp.x + y, y: comp.y + l.w - x };
    default:
      return { x: comp.x + x, y: comp.y + y };
  }
}

/** The SVG transform that puts a component's own frame at the right place. */
export function transformOf(comp: PlacedComponent, l: Layout): string {
  const t =
    comp.rot === 90
      ? { x: l.h, y: 0 }
      : comp.rot === 180
        ? { x: l.w, y: l.h }
        : comp.rot === 270
          ? { x: 0, y: l.w }
          : { x: 0, y: 0 };
  return `translate(${comp.x + t.x} ${comp.y + t.y}) rotate(${comp.rot})`;
}

/** Which way a wire should leave a pin, after rotation. */
export function worldSide(side: PinPos['side'], rot: number): PinPos['side'] {
  const order: PinPos['side'][] = ['T', 'R', 'B', 'L'];
  const i = order.indexOf(side);
  return order[(i + rot / 90) % 4];
}

export function pinWorldPos(
  model: ComponentModel,
  comp: PlacedComponent,
  pin: number,
): { x: number; y: number; side: PinPos['side'] } | null {
  const l = layoutOf(model, comp);
  const p = l.pins.find((q) => q.n === pin);
  if (!p) return null;
  const w = toWorld(comp, l, p.x, p.y);
  return { ...w, side: worldSide(p.side, comp.rot) };
}

export const snapTo = (v: number, step = GRID) => Math.round(v / step) * step;
