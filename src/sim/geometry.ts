/**
 * Where every pin physically sits.
 *
 * Geometry is kept out of the React components so that hit-testing, wire
 * routing, breadboard hole contact and rendering all agree on one set of
 * coordinates. All values are in workspace units (1 unit = 1 px at zoom 1).
 */
import type { ComponentModel, PlacedComponent } from './types';

export const GRID = 10;
/** 0.1 inch pin pitch, and the breadboard hole pitch. */
export const PIN_PITCH = 20;

const DIP_BODY_W = 100;
const DIP_LEG = 15;
export const DIP_W = DIP_BODY_W + DIP_LEG * 2; // 130
const DIP_PAD = 15;

export interface PinPos {
  n: number;
  x: number;
  y: number;
  side: 'L' | 'R' | 'T' | 'B';
}

export interface Layout {
  w: number;
  h: number;
  pins: PinPos[];
  /** The drawn body, inset from the bounding box by the pin legs. */
  bodyX: number;
  bodyY: number;
  bodyW: number;
  bodyH: number;
}

function dipLayout(pinCount: number): Layout {
  const perSide = pinCount / 2;
  const h = 2 * (DIP_PAD + 10) + (perSide - 1) * PIN_PITCH;
  const pins: PinPos[] = [];
  for (let i = 1; i <= perSide; i++) {
    pins.push({ n: i, x: 0, y: DIP_PAD + 10 + (i - 1) * PIN_PITCH, side: 'L' });
  }
  for (let i = 1; i <= perSide; i++) {
    pins.push({
      n: perSide + i,
      x: DIP_W,
      y: DIP_PAD + 10 + (perSide - i) * PIN_PITCH,
      side: 'R',
    });
  }
  return {
    w: DIP_W,
    h,
    pins,
    bodyX: DIP_LEG,
    bodyY: 0,
    bodyW: DIP_BODY_W,
    bodyH: h,
  };
}

type ModuleSpec = { w: number; h: number; pins: PinPos[] };

/**
 * Module pins sit on the same 0.1 inch pitch as the breadboard holes, and every
 * pin of a part is a whole number of pitches from its first pin. That is what
 * lets any part - not just a DIP - drop into the board with every leg seated.
 */
function stack(count: number, x: number, side: 'L' | 'R', top: number, pitch = PIN_PITCH): PinPos[] {
  return Array.from({ length: count }, (_, i) => ({ n: i + 1, x, y: top + i * pitch, side }));
}

